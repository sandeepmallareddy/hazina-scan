"""Structure metrics: the tree-sitter lane.

The concentration figure is a share of a distribution built by walking every parse tree in
the repository, so a single node name missing from a table, or one directory pruned that
should not have been, moves the number without raising anything. The fixtures below are
therefore one per edge the walk has, and each assertion says what its fixture is for.
"""

from __future__ import annotations

import sys

import pytest

from hazina_scan import structure

# --- the trees, one per edge the walk has ------------------------------------------

#: Five grammars and a tier the parser cannot reach: Python, TypeScript, Go, Rust, a
#: notebook whose code cells are the only thing counted, and a Vala file that raises the
#: file and line counts without ever being handed to a parser.
